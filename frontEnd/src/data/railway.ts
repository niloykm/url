// Helper calculations
export function calculateFares(distanceKm: number, seatClasses: SeatClass[]): Record<SeatClass, { base: number; vat: number; fee: number; total: number; available: number }> {
  // Official standard BR rate baseline: ~1.2 BDT per km for Shovan Chair, scaled
  const baseRatePerKm = 1.15;
  const result = {} as Record<SeatClass, { base: number; vat: number; fee: number; total: number; available: number }>;

  seatClasses.forEach((sc) => {
    const meta = SEAT_CLASS_META[sc] || { baseMultiplier: 1.0 };
    // Base fare rounded to nearest 5
    const rawBase = Math.round((distanceKm * baseRatePerKm * meta.baseMultiplier) / 5) * 5;
    const baseFare = Math.max(rawBase, 50);
    // 15% VAT on AC classes (SNIGDHA, AC_S, AC_B) according to BR taxation policy
    const isAc = ['SNIGDHA', 'AC_S', 'AC_B'].includes(sc);
    const vat = isAc ? Math.round(baseFare * 0.15) : 0;
    const fee = 50; // standard ৳50 BR issuance/portal facilitation charge
    const total = baseFare + vat + fee;

    // Realistic seat availability simulation
    let available = 0;
    if (sc === 'S_CHAIR') available = Math.floor(Math.sin(distanceKm) * 35 + 45);
    else if (sc === 'SNIGDHA') available = Math.floor(Math.cos(distanceKm) * 20 + 25);
    else if (sc === 'SHOVAN') available = Math.floor(Math.sin(distanceKm + 1) * 60 + 70);
    else if (sc === 'AC_B') available = Math.floor(Math.cos(distanceKm + 2) * 8 + 10);
    else available = 15;

    result[sc] = {
      base: baseFare,
      vat,
      fee,
      total,
      available: Math.max(available, 0),
    };
  });

  return result;
}

